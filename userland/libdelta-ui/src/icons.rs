pub fn draw_icon_2x(canvas: &mut Canvas, x: i32, y: i32, kind: IconKind, color: u32) {
    let bitmap = rows(kind);
    for (r, &bits) in bitmap.iter().enumerate() {
        for c in 0..16 {
            if (bits & (0x8000 >> c)) != 0 {
                canvas.fill_rect(x + c * 2, y + (r as i32) * 2, 2, 2, color);
            }
        }
    }
}
