//! Original GNU GPL v3.0 humanist proportional font (Calibri-inspired) and
//! crisp `8x14` monospace console font for Hollow Star OS+.
//!
//! Coordinate grid (`14` rows):
//! - Rows `0..=1`: Uppercase diacritics (`Ć Ń Ó Ś Ź Ż`)
//! - Row `2`: Ascender tops (`b d f h k l`) & start of lowercase accents
//! - Rows `3..=10`: Uppercase letters (`8px` cap height, baseline at row `10`)
//! - Rows `5..=10`: Lowercase x-height (`6px` body height)
//! - Rows `11..=12`: Descenders (`g j p q y`) & Polish ogonek (`ą ę Ą Ę`)
//! - Row `13`: Bottom breathing room (`line_height = 15..=16px`)

/// Height of all `libdelta-ui` bitmap glyphs in logical pixels.
pub const FONT_HEIGHT: i32 = 14;
/// Fixed horizontal advance of `glyph_mono` cells.
pub const MONO_WIDTH: i32 = 8;

/// Proportional `14`-row bitmap glyph (MSB of `rows[r]` corresponds to column `0`).
#[derive(Clone, Copy)]
pub struct Glyph14 {
    pub width: u8,
    pub advance: u8,
    pub rows: [u16; 14],
}

const fn parse_prop(advance: u8, lines: [&str; 14]) -> Glyph14 {
    let mut rows = [0u16; 14];
    let mut max_w = 0usize;
    let mut r = 0usize;
    while r < 14 {
        let bytes = lines[r].as_bytes();
        let len = if bytes.len() > 16 { 16 } else { bytes.len() };
        if len > max_w {
            max_w = len;
        }
        let mut mask = 0u16;
        let mut c = 0usize;
        while c < len {
            if bytes[c] != b'.' && bytes[c] != b' ' {
                mask |= 1u16 << (15 - c);
            }
            c += 1;
        }
        rows[r] = mask;
        r += 1;
    }
    Glyph14 {
        width: max_w as u8,
        advance,
        rows,
    }
}

const fn parse_mono(lines: [&str; 14]) -> [u8; 14] {
    let mut rows = [0u8; 14];
    let mut r = 0usize;
    while r < 14 {
        let bytes = lines[r].as_bytes();
        let len = if bytes.len() > 8 { 8 } else { bytes.len() };
        let mut mask = 0u8;
        let mut c = 0usize;
        while c < len {
            if bytes[c] != b'.' && bytes[c] != b' ' {
                mask |= 1u8 << (7 - c);
            }
            c += 1;
        }
        rows[r] = mask;
        r += 1;
    }
    rows
}

macro_rules! g {
    ($adv:expr, [
        $r0:literal, $r1:literal, $r2:literal, $r3:literal,
        $r4:literal, $r5:literal, $r6:literal, $r7:literal,
        $r8:literal, $r9:literal, $r10:literal, $r11:literal,
        $r12:literal, $r13:literal
    ]) => {
        const {
            parse_prop(
                $adv,
                [
                    $r0, $r1, $r2, $r3, $r4, $r5, $r6, $r7, $r8, $r9, $r10, $r11, $r12, $r13,
                ],
            )
        }
    };
}

macro_rules! m {
    ([
        $r0:literal, $r1:literal, $r2:literal, $r3:literal,
        $r4:literal, $r5:literal, $r6:literal, $r7:literal,
        $r8:literal, $r9:literal, $r10:literal, $r11:literal,
        $r12:literal, $r13:literal
    ]) => {
        const {
            parse_mono([
                $r0, $r1, $r2, $r3, $r4, $r5, $r6, $r7, $r8, $r9, $r10, $r11, $r12, $r13,
            ])
        }
    };
}

/// Measures rendered width of `text` using the Calibri-styled proportional font at `scale`.
pub fn measure_calibri(text: &str, scale: i32) -> i32 {
    let s = scale.max(1);
    let mut w = 0i32;
    for ch in text.chars() {
        w += i32::from(glyph_calibri(ch).advance) * s;
    }
    w
}

