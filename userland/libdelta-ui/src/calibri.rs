#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn printable_and_polish_glyphs_have_ink_and_valid_advance() {
        for ch in '!'..='~' {
            let g = glyph_calibri(ch);
            assert!(g.advance >= 3 && g.advance <= 10, "bad advance on {ch}");
            assert!(
                g.rows.iter().any(|&r| r != 0),
                "empty calibri glyph on {ch}"
            );
            let m = glyph_mono(ch);
            assert!(m.iter().any(|&r| r != 0), "empty mono glyph on {ch}");
        }
        for ch in [
            'ą', 'ć', 'ę', 'ł', 'ń', 'ó', 'ś', 'ź', 'ż', 'Ą', 'Ć', 'Ę', 'Ł', 'Ń', 'Ó', 'Ś', 'Ź',
            'Ż',
        ] {
            let g = glyph_calibri(ch);
            assert!(
                g.rows.iter().any(|&r| r != 0),
                "empty calibri glyph on {ch}"
            );
            let m = glyph_mono(ch);
            assert!(m.iter().any(|&r| r != 0), "empty mono glyph on {ch}");
        }
        assert_eq!(glyph_calibri(' ').advance, 4);
        assert!(measure_calibri("Hollow Star", 1) > 40);
    }
}
